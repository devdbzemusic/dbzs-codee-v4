import type { AppSettings } from "@dbzs/shared";
import { DEFAULT_SETTINGS } from "@dbzs/shared";

export type SettingsCategory =
  | "general"
  | "models"
  | "runtime"
  | "agents_safety"
  | "context_rag"
  | "workspace_editor"
  | "backend"
  | "advanced"
  | "diagnostics";

export type SettingClassification =
  | "user_tunable"
  | "advanced_user_tunable"
  | "secret"
  | "internal_feature_flag"
  | "hard_invariant"
  | "read_only_diagnostic"
  | "orphaned"
  | "deprecated";

export type SettingControl =
  | "toggle"
  | "number"
  | "range"
  | "text"
  | "password"
  | "select"
  | "path"
  | "model_select"
  | "readonly"
  | "percent";

export interface SettingDefinition<T = unknown> {
  key: keyof AppSettings;
  category: SettingsCategory;
  label: string;
  description: string;
  classification: SettingClassification;
  defaultValue: T;
  control: SettingControl;
  validation?: {
    min?: number;
    max?: number;
    step?: number;
    options?: Array<{ value: string; label: string }>;
    maxLength?: number;
  };
  restartRequirement:
    | "none"
    | "next_run"
    | "runtime_restart"
    | "backend_restart"
    | "app_restart";
  sensitive?: boolean;
  experimental?: boolean;
  environmentOverrides?: string[];
  consumerDescription: string;
}

const d = DEFAULT_SETTINGS;

function def<K extends keyof AppSettings>(
  partial: SettingDefinition<AppSettings[K]>,
): SettingDefinition {
  return partial as SettingDefinition;
}

