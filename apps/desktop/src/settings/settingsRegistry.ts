export function getSettingDefinition(key: keyof AppSettings): SettingDefinition | undefined {
  return SETTINGS_REGISTRY.find((entry) => entry.key === key);
}

export function settingsByCategory(category: SettingsCategory): SettingDefinition[] {
  return SETTINGS_REGISTRY.filter((entry) => entry.category === category);
}

export function userTunableSettings(): SettingDefinition[] {
  return SETTINGS_REGISTRY.filter((entry) =>
    ["user_tunable", "advanced_user_tunable", "secret"].includes(entry.classification),
  );
}

export function isEditableClassification(classification: SettingClassification): boolean {
  return (
    classification === "user_tunable" ||
    classification === "advanced_user_tunable" ||
    classification === "secret" ||
    classification === "internal_feature_flag"
  );
}
